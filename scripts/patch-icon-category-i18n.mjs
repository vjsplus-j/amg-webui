const order = Object.keys(labels['en-US']).sort((a, b) => a.localeCompare(b))

for (const loc of Object.keys(labels)) {
  const file = path.join(root, 'packages/locale', loc, 'exampleDoc.ts')
  let text = fs.readFileSync(file, 'utf8')
  text = text.replace(/\s*"example\.doc\.icon\.category\.[^"]+":\s*"[^"]*",?/g, '')

  const block = order
    .map((k) => `  "example.doc.icon.category.${k}": ${JSON.stringify(labels[loc][k])},`)
    .join('\n')

  const insertAt = text.search(/\n\s*"example\.doc\.icon\./)
  if (insertAt < 0) {
    throw new Error(`No example.doc.icon.* anchor in ${file}`)
  }
  text = text.slice(0, insertAt) + '\n' + block + text.slice(insertAt)
  fs.writeFileSync(file, text, 'utf8')

  const count = (text.match(/example\.doc\.icon\.category\./g) || []).length
  console.log(loc, count)
}
