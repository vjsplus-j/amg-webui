/**
 * Compile component-metadata/*.json → example/generated/component-metadata.ts
 *
 * Usage:
 *   node scripts/generate-example-metadata.mjs
 *   node scripts/generate-example-metadata.mjs --all
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toKebab } from '../build/shared.mjs'
import { P0_COMPONENTS, parseDisplayTitle } from './component-docs-constants.mjs'
import { FOUNDATION_PACKAGES } from './component-package-map.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const metaDir = join(root, 'component-metadata')
const outDir = join(root, 'example/generated')
const outFile = join(outDir, 'component-metadata.ts')
const docsComponentsDir = join(root, 'docs/components')

function loadMetadataFiles() {
  if (!existsSync(metaDir)) return []
  return readdirSync(metaDir)
    .filter((f) => f.endsWith('.json') && f !== 'index.json' && f !== 'schema.json')
    .map((f) => f.replace(/\.json$/, ''))
    .sort()
}

function normalizeRecord(name, raw) {
  const slug = raw.docsSlug || toKebab(name)
  const docsPage = join(docsComponentsDir, `${slug}.md`)
  const { title, titleZh } = parseDisplayTitle(name, raw.title)
  const importFrom =
    (Array.isArray(raw.importPaths) && raw.importPaths[0]) ||
    raw.importFrom ||
    `amg-webui/${raw.package || 'core'}`

  return {
    name: raw.name || name,
    title,
    titleZh,
    summary: raw.summary || '',
    description: raw.description,
    features: raw.features,
    useCases: raw.useCases,
    avoidWhen: raw.avoidWhen,
    package: raw.package,
    maturity: raw.maturity,
    importFrom,
    importPaths: raw.importPaths,
    docsSlug: slug,
    hasDocsPage: existsSync(docsPage),
    docsPath: `components/${slug}`,
    related: raw.related,
    limitations: raw.limitations
  }
}

function emitTs(records) {
  const map = Object.fromEntries(records.map((rec) => [rec.name, rec]))
  return `/** Auto-generated by scripts/generate-example-metadata.mjs — do not edit. */

export interface ComponentMetadata {
  name: string
  title: string
  titleZh: string
  summary: string
  description?: string
  features?: string[]
  useCases?: string[]
  avoidWhen?: string[]
  package: string
  maturity?: string
  importFrom: string
  importPaths?: string[]
  docsSlug?: string
  docsPath?: string
  hasDocsPage?: boolean
  related?: string[]
  limitations?: string[]
}

export const COMPONENT_METADATA: Record<string, ComponentMetadata> = ${JSON.stringify(map, null, 2)}

export function getComponentMetadata(name: string): ComponentMetadata | undefined {
  return COMPONENT_METADATA[name]
}
`
}

function main() {
  const available = loadMetadataFiles()
  let target
  if (process.argv.includes('--foundation-only')) {
    target = available.filter((name) => {
      try {
        const meta = JSON.parse(readFileSync(join(metaDir, `${name}.json`), 'utf8'))
        return FOUNDATION_PACKAGES.includes(meta.package)
      } catch {
        return false
      }
    })
  } else if (process.argv.includes('--core-set')) {
    target = P0_COMPONENTS.filter((n) => available.includes(n))
  } else {
    // Default: all public component metadata (DOCS-PUBLIC-API SSOT → Example)
    target = available
  }

  if (!target.length) {
    console.error(
      '[generate-example-metadata] no metadata files found — run npm run generate:component-metadata first'
    )
    process.exit(1)
  }

  const records = target.map((name) =>
    normalizeRecord(name, JSON.parse(readFileSync(join(metaDir, `${name}.json`), 'utf8')))
  )
  mkdirSync(outDir, { recursive: true })
  writeFileSync(outFile, emitTs(records), 'utf8')
  console.log(`[write] example/generated/component-metadata.ts (${records.length} components)`)
}

main()
