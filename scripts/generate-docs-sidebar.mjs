/**
 * Generate VitePress component sidebar from catalog + maturity + docs metadata (SSOT).
 *
 * Usage: node scripts/generate-docs-sidebar.mjs
 * Output: docs/.vitepress/sidebar.components.ts
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toKebab } from '../build/shared.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'docs/.vitepress/sidebar.components.ts')

/** v0.1 documented core — priority ordering */
const V01_PRIORITY = [
  'Button',
  'Select',
  'DataTable',
  'Tree',
  'Form',
  'Dialog',
  'InputText',
  'Checkbox',
  'Switch',
  'Pagination',
  'Layout',
  'Menu',
  'Tabs',
  'Alert',
  'MessageBox',
  'ConfigProvider',
  'Segmented',
  'Affix',
  'Image',
  'Tour'
]

const CATEGORY_LABELS = {
  general: '通用',
  layout: '布局',
  navigation: '导航',
  'data-entry': '数据录入',
  'data-display': '数据展示',
  feedback: '反馈',
  other: '其它',
  industry: '行业'
}

function loadJson(rel) {
  const p = join(root, rel)
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null
}

function loadVerifiedStable() {
  const stable = loadJson('component-hardening/reports/stable-components.json')
  if (Array.isArray(stable?.components)) return new Set(stable.components)
  const ps = loadJson('component-hardening/program-status.json')
  if (Array.isArray(ps?.hardening?.stableComponents)) {
    return new Set(ps.hardening.stableComponents)
  }
  return new Set()
}

function loadMaturityMap() {
  const maturity = loadJson('component-hardening/inventory/component-maturity-v4.json')
  const map = new Map()
  if (maturity?.components) {
    for (const [name, row] of Object.entries(maturity.components)) {
      map.set(name, row.maturity || 'beta')
    }
  }
  return map
}

function hasDocPage(name) {
  return existsSync(join(root, 'docs/components', `${toKebab(name)}.md`))
}

function labelFor(name, verifiedStable, maturityMap) {
  if (verifiedStable.has(name)) return `${name} ★`
  const m = maturityMap.get(name)
  if (m === 'rc' || m === 'rc-candidate') return `${name} (rc)`
  if (m === 'shell' || m === 'stub') return `${name} (shell)`
  return name
}

function item(name, verifiedStable, maturityMap) {
  return {
    text: labelFor(name, verifiedStable, maturityMap),
    link: `/components/${toKebab(name)}`
  }
}

function buildSidebarItems() {
  const catalog = loadJson('example/component-catalog.json')
  if (!catalog?.byCategory) {
    throw new Error('missing example/component-catalog.json byCategory')
  }

  const verifiedStable = loadVerifiedStable()
  const maturityMap = loadMaturityMap()
  const items = [{ text: '概览', link: '/components/' }]

  const v01 = V01_PRIORITY.filter((n) => hasDocPage(n)).map((n) =>
    item(n, verifiedStable, maturityMap)
  )
  items.push({ text: '—— v0.1 核心 ——', link: '/components/' }, ...v01)

  const listed = new Set(V01_PRIORITY)
  for (const category of catalog.categories || Object.keys(catalog.byCategory)) {
    const names = (catalog.byCategory[category] || [])
      .filter((n) => !listed.has(n) && hasDocPage(n))
      .sort()
    if (!names.length) continue
    const label = CATEGORY_LABELS[category] || category
    items.push({ text: `—— ${label} ——`, link: '/components/' })
    for (const n of names) {
      items.push(item(n, verifiedStable, maturityMap))
      listed.add(n)
    }
  }

  return items
}

function emitTs(items) {
  const lines = items.map((i) => {
    const text = i.text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
    return `    { text: '${text}', link: '${i.link}' }`
  })
  return `// AUTO-GENERATED by scripts/generate-docs-sidebar.mjs — do not edit manually.
// SSOT: example/component-catalog.json + component-maturity-v4 + stable-components + docs/components/*.md
// Regenerate: npm run generate:docs-sidebar

export const componentSidebarGroup = {
  text: '组件',
  items: [
${lines.join(',\n')}
  ]
}
`
}

function main() {
  const items = buildSidebarItems()
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, emitTs(items), 'utf8')
  console.log(`[generate:docs-sidebar] wrote ${items.length} items → docs/.vitepress/sidebar.components.ts`)
}

main()
